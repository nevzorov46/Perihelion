import Foundation

// Bakes the campaign: for every sky, tries many seeds and keeps the best shot.
// Run through tools/run.sh bake - it writes the output to Perihelion/Game/Levels.swift.

let seeds = 24
var report: [String] = []
var entries: [String] = []

func literal(_ spec: BodySpec) -> String {
    switch spec {
    case let .fixed(kind, x, y, mu):
        return ".fixed(.\(kind), x: \(x), y: \(y), mu: \(mu))"
    case let .orbiting(kind, around, radius, phase, direction, mu):
        return ".orbiting(.\(kind), around: \(around), radius: \(radius), phase: \(phase), direction: \(direction), mu: \(mu))"
    case let .binary(x, y, separation, mu1, mu2, phase, direction):
        return ".binary(x: \(x), y: \(y), separation: \(separation), mu1: \(mu1), mu2: \(mu2), phase: \(phase), direction: \(direction))"
    case let .threeBody(x, y, scale, period, rotation, phase):
        return ".threeBody(x: \(x), y: \(y), scale: \(scale), period: \(period), rotation: \(rotation), phase: \(phase))"
    }
}

func quoted(_ s: String) -> String {
    "\"" + s.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"") + "\""
}

for sky in campaign {
    let level = Level(sky.def)
    var best: Design.Result?
    for seed in 1...seeds {
        var random = SeededRandom(seed: UInt32(seed * 7919))
        if let result = Design.design(level, brief: sky.brief, random: &random),
           best.map({ sky.prefer(result) > sky.prefer($0) }) ?? true {
            best = result
        }
    }
    guard let best else {
        report.append("\(sky.def.id): NO DESIGN FOUND")
        continue
    }
    let window = (best.window * 100).rounded() / 100
    report.append("\(sky.def.id): window \(window), turn \((best.turn * 100).rounded() / 100) rad, length \(Int(best.length))")
    let d = sky.def
    entries.append("""
            LevelDef(
                id: \(quoted(d.id)), name: \(quoted(d.name)),
                hint: \(quoted(d.hint)),
                root: \(d.root), preview: \(d.preview),
                bodies: [\(d.bodies.map(literal).joined(separator: ", "))],
                launch: SIMD2(\(d.launch.x), \(d.launch.y)),
                motes: [\(best.motes.map { "SIMD2(\($0.x), \($0.y))" }.joined(separator: ", "))],
                shot: Shot(angle: \(best.shot.angle), speed: \(best.shot.speed)),
                window: \(window)
            ),
    """)
}

print("// Generated by tools/run.sh bake from tools/bake/Campaign.swift - do not edit by hand.")
print("// Every level carries `shot`: a launch that collects every mote, its proof of solvability.")
for line in report { print("//   \(line)") }
print("")
print("extension LevelDef {")
print("    static let campaign: [LevelDef] = [")
for entry in entries { print(entry) }
print("    ]")
print("}")
